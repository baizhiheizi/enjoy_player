function storedLanguage() {
  try {
    return localStorage.getItem('enjoy_lang');
  } catch {
    return null;
  }
}

function storeLanguage(lang) {
  try {
    localStorage.setItem('enjoy_lang', lang);
  } catch {
    /* storage unavailable: the choice lasts for this page view */
  }
}

function setMeta(selector, value) {
  const el = document.querySelector(selector);
  if (el) el.content = value;
}

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  const table = translations[lang];
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  storeLanguage(lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = table[el.getAttribute('data-i18n')];
    if (value === undefined) return;
    if (value.includes('<')) el.innerHTML = value;
    else el.textContent = value;
  });

  document.querySelectorAll('[data-alt-i18n]').forEach((el) => {
    const value = table[el.getAttribute('data-alt-i18n')];
    if (value) el.alt = value;
  });

  // data-version is stamped by main.js once the manifest names the build a
  // button downloads; screen readers then hear "(vX.Y.Z)" too.
  document.querySelectorAll('[data-aria-i18n]').forEach((el) => {
    const base = table[el.getAttribute('data-aria-i18n')];
    if (!base) return;
    const version = el.dataset.version;
    el.setAttribute('aria-label', version ? `${base} (v${version})` : base);
  });

  document.title = table['meta.title'];
  setMeta('meta[property="og:title"]', table['meta.title']);
  setMeta('meta[name="twitter:title"]', table['meta.title']);
  setMeta('meta[name="description"]', table['meta.desc']);

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });

  document.dispatchEvent(new CustomEvent('enjoy:language', { detail: { lang } }));
}

function currentLanguage() {
  return document.documentElement.lang.startsWith('zh') ? 'zh' : 'en';
}

function t(key) {
  return translations[currentLanguage()][key] ?? translations.en[key] ?? '';
}

function initI18n() {
  let lang = storedLanguage();
  if (!lang) {
    const browserLang = navigator.language || '';
    lang = browserLang.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLanguage(btn.dataset.lang);
    });
  });

  setLanguage(lang);
}

window.initI18n = initI18n;
window.setLanguage = setLanguage;
window.currentLanguage = currentLanguage;
window.t = t;
window.translations = translations;
